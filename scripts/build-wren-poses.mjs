// Assemble src/assets/wren-poses.ts from the traced pose paths.
//
// This is step 3 of the character regeneration chain (P13):
//   reference art -> docs/design/wren-character/trace.mjs -> *.paths.txt
//     -> THIS SCRIPT -> src/assets/wren-poses.ts -> wren-figure.tsx
//
// Run it whenever a trace changes or a new pose joins MANIFEST:
//   node scripts/build-wren-poses.mjs           # writes the module
//   node scripts/build-wren-poses.mjs --check   # exit 1 if the module is stale
//
// Trace line format (one component per line):
//   BODY <path d>            the white silhouette
//   WING <path d>            brand pink
//   BEAK <path d>            brand pink
//   EYE bbox x0,y0,x1,y1     the eye pill; wren-figure draws it from the bbox
//   PALE<n> n=<px> <path d>  pale details, emitted in trace order

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const TRACES = join(ROOT, 'docs/design/wren-character')
const OUT = join(ROOT, 'src/assets/wren-poses.ts')

// The poses the rig renders, by trace basename; each exports as
// WREN_<BASENAME>. Traces not listed here (the preens, the turnaround when it
// lands) stay out of the module until their choreography exists — add the
// basename and re-run.
const MANIFEST = ['perched', 'flight']

const exportName = (file) => `WREN_${file.toUpperCase().replaceAll('-', '_')}`

function parseTrace(file) {
  const pose = { body: null, pink: [], pale: [], eye: null }
  for (const line of readFileSync(join(TRACES, `${file}.paths.txt`), 'utf8').split('\n')) {
    if (!line.trim()) continue
    const label = line.slice(0, line.indexOf(' '))
    const rest = line.slice(label.length + 1)
    if (label === 'BODY') pose.body = rest
    else if (label === 'WING' || label === 'BEAK') pose.pink.push(rest)
    else if (label === 'EYE') pose.eye = rest.replace('bbox ', '').split(',').map(Number)
    else if (/^PALE\d+$/.test(label)) pose.pale.push(rest.replace(/^n=\d+ /, ''))
    else throw new Error(`${file}.paths.txt: unknown label ${label}`)
  }
  for (const [key, value] of Object.entries(pose)) {
    if (value === null || (Array.isArray(value) && value.length === 0))
      throw new Error(`${file}.paths.txt: no ${key.toUpperCase()} component`)
  }
  if (pose.eye.length !== 4 || pose.eye.some(Number.isNaN))
    throw new Error(`${file}.paths.txt: EYE bbox is not four numbers`)
  return pose
}

const quoted = (s) => JSON.stringify(s)

function emitPose(name, pose) {
  return [
    `export const ${name}: WrenPose = {`,
    `  body: ${quoted(pose.body)},`,
    `  pink: [${pose.pink.map(quoted).join(', ')}],`,
    `  pale: [${pose.pale.map(quoted).join(', ')}],`,
    `  eye: [${pose.eye.join(', ')}],`,
    `}`,
  ].join('\n')
}

const module_ = [
  `// GENERATED by scripts/build-wren-poses.mjs from`,
  `// docs/design/wren-character/*.paths.txt — Nick's canonical character art,`,
  `// pixel-traced with trace.mjs. Do not edit by hand; edit the traces or the`,
  `// manifest and re-run. ViewBox 0 0 440 440.`,
  ``,
  `export interface WrenPose {`,
  `  /** The white silhouette. */`,
  `  body: string`,
  `  /** Wing + beak, the brand pink. */`,
  `  pink: string[]`,
  `  /** Legs, underfeathers, sparkles — the pale details. */`,
  `  pale: string[]`,
  `  /** Eye pill bbox [x0, y0, x1, y1]. */`,
  `  eye: [number, number, number, number]`,
  `}`,
  ``,
  MANIFEST.map((file) => emitPose(exportName(file), parseTrace(file))).join('\n\n'),
  ``,
].join('\n')

if (process.argv.includes('--check')) {
  const current = readFileSync(OUT, 'utf8')
  if (current === module_) {
    console.log('wren-poses.ts is up to date')
  } else {
    console.error('wren-poses.ts is stale — run node scripts/build-wren-poses.mjs')
    process.exit(1)
  }
} else {
  writeFileSync(OUT, module_)
  console.log(`wrote ${MANIFEST.length} poses to src/assets/wren-poses.ts`)
}
